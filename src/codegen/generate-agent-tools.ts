// Generates, from src/agent_tools/tools.json and src/agent_tools/skills.json:
//
// - src/agent_tools/generated/tools.rs: the `tools/list` descriptors of `bun mcp`'s agent tools;
// - docs/project/agent-tools.mdx: their reference, and the list of generated skills;
// - .claude/skills/<name>/SKILL.md: one skill per entry of skills.json, every section extracted from the
//   repository (docs, CLAUDE.md, module docs, package.json scripts, the `bun lsp` sources).
//
// The outputs are checked in, so `cargo check`, `bun mcp` (which embeds .claude/skills and docs/) and the
// agent plugin (packages/bun-agent-plugin, which reads .claude/skills) need no build step. Same inputs, same
// bytes. Runs under Bun and Node (the build's codegen may run under either).
//
//   bun src/codegen/generate-agent-tools.ts            write the outputs
//   bun src/codegen/generate-agent-tools.ts --check    exit 1 when an output is stale
//   bun src/codegen/generate-agent-tools.ts --inputs   print the input files, one per line
//   --tools <file> --skills <file> --out <dir>         other sources or output root (tests)

