// Regenerates the n2b report types from the canonical JSON Schema:
//   - crates/n2b-types/src/schema.rs  via `cargo typify`
//   - src/types.ts                    via `json2ts --unreachableDefinitions` (json-schema-to-typescript)
// Both files are committed; --check exits 1 on drift.
//
//   bun packages/bun-n2b/scripts/generate-schema-types.ts [--check]

import { $ } from "bun";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const PKG = resolve(import.meta.dir, "..");

export async function schemaPaths(root = PKG) {
  const crate = join(root, "crates/n2b-types");
  const schema = join(crate, "schema/v2.json");
  if (!(await Bun.file(schema).exists())) {
    throw new Error(`Canonical N2B schema missing: ${schema}`);
  }
  return {
    schema,
    rust: join(crate, "src/schema.rs"),
    format: join(root, "rustfmt.toml"),
    ts: join(root, "src/types.ts"),
  };
}

type SchemaPaths = Awaited<ReturnType<typeof schemaPaths>>;

const BANNER_RS = `// @generated — DO NOT EDIT MANUALLY.
// Regenerate with: bun packages/bun-n2b/scripts/generate-schema-types.ts
// Source of truth: packages/bun-n2b/crates/n2b-types/schema/v2.json

`;

const BANNER_TS = `// @generated — DO NOT EDIT MANUALLY.
// Regenerate with: bun packages/bun-n2b/scripts/generate-schema-types.ts
// Source of truth: packages/bun-n2b/crates/n2b-types/schema/v2.json

`;

const HEADER_TS_REGEX =
  /^\/\* eslint-disable \*\/\n\/\*\*\n \* This file was automatically generated by json-schema-to-typescript\.\n \* DO NOT MODIFY IT BY HAND\. Instead, modify the source JSONSchema file,\n \* and run json-schema-to-typescript to regenerate this file\.\n \*\/\n/;

async function generateRust(paths: SchemaPaths): Promise<string> {
  const tmp = join(tmpdir(), `n2b-schema-${process.pid}.rs`);
  const result = await $`cargo typify -o ${tmp} ${paths.schema}`.quiet();
  if (result.exitCode !== 0) {
    throw new Error(`cargo typify failed: ${result.stderr.toString()}`);
  }
  // Format with the repository rustfmt policy so the committed file is also `cargo fmt --check`
  // clean and `--check` compares like with like.
  const fmt = await $`rustfmt --config-path ${paths.format} ${tmp}`.quiet().nothrow();
  if (fmt.exitCode !== 0) {
    throw new Error(`rustfmt failed: ${fmt.stderr.toString()}`);
  }
  const body = await Bun.file(tmp).text();
  await Bun.file(tmp).delete();
  return BANNER_RS + body;
}

export async function generateTs(paths: SchemaPaths): Promise<string> {
  const result = await $`json2ts --unreachableDefinitions < ${Bun.file(paths.schema)}`.quiet();
  if (result.exitCode !== 0) {
    throw new Error(`json-schema-to-typescript failed: ${result.stderr.toString()}`);
  }
  const out = result.stdout.toString();
  if (!HEADER_TS_REGEX.test(out)) {
    throw new Error("json-schema-to-typescript output header changed; update HEADER_TS_REGEX");
  }
  return BANNER_TS + out.replace(HEADER_TS_REGEX, "").replace(/^\n+/, "");
}

async function main(): Promise<void> {
  const paths = await schemaPaths();
  const check = process.argv.includes("--check");
  const [rust, ts] = await Promise.all([generateRust(paths), generateTs(paths)]);

  if (check) {
    const [rustCommitted, tsCommitted] = await Promise.all([Bun.file(paths.rust).text(), Bun.file(paths.ts).text()]);
    let drift = false;
    if (rust !== rustCommitted) {
      console.error(`drift: ${paths.rust}`);
      drift = true;
    }
    if (ts !== tsCommitted) {
      console.error(`drift: ${paths.ts}`);
      drift = true;
    }
    if (drift) {
      console.error("\nRun `bun packages/bun-n2b/scripts/generate-schema-types.ts` and commit the regenerated files.");
      process.exit(1);
    }
    console.log("n2b:codegen:check OK — no drift");
    return;
  }

  await Promise.all([Bun.write(paths.rust, rust), Bun.write(paths.ts, ts)]);
  console.log(`wrote ${paths.rust}`);
  console.log(`wrote ${paths.ts}`);
}

if (import.meta.main)
  main().catch(err => {
    console.error(err);
    process.exit(1);
  });
