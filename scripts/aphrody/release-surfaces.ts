export function digest(data: string | Uint8Array): string {
  return createHash("sha256").update(data).digest("hex");
}

export function artifactPaths(out: string): string[] {
  return [...new Bun.Glob("**/*").scanSync({ cwd: out, onlyFiles: true })]
    .map(path => path.replaceAll(String.fromCharCode(92), "/"))
    .filter(
      path =>
        path !== "source.tar" &&
        path !== "manifest.json" &&
        !path.startsWith("source/") &&
        !/\.sqlite-(?:wal|shm)$/.test(path),
    )
    .sort();
}

export function refreshManifest(out: string) {
  const manifest = JSON.parse(readFileSync(join(out, "manifest.json"), "utf8"));
  const graph = JSON.parse(readFileSync(join(out, "graph.json"), "utf8"));
  if (graph.source !== manifest.source) throw new Error("Graph and artifact source revisions differ");
  const supplemented = new Set<string>();
  if (existsSync(join(out, "knowledge-coverage.json"))) {
    const knowledge = JSON.parse(readFileSync(join(out, "knowledge-coverage.json"), "utf8"));
    if (
      knowledge.source !== manifest.source ||
      knowledge.generatorSha256 !== digest(readFileSync(join(import.meta.dir, "release-knowledge.ts")))
    )
      throw new Error("Supplemental generation provenance differs");
    for (const path of knowledge.changed) supplemented.add(path);
  }
  const artifacts: Record<string, string> = {};
  for (const path of artifactPaths(out)) {
    const hash = digest(readFileSync(join(out, path)));
    const expected = manifest.artifacts[path] ?? manifest.artifacts[path.replaceAll("/", String.fromCharCode(92))];
    if (hash !== expected && !supplemented.has(path)) throw new Error(`Existing artifact changed: ${path}`);
    artifacts[path] = hash;
  }
  const updated = { ...manifest, artifacts };
  writeFileSync(join(out, "manifest.json"), `${JSON.stringify(updated, null, 2)}\n`);
  return updated;
}

export async function regenerate(root: string, ref: string, out: string, repo: string, offline: boolean) {
  const tree = new GitTree(root, ref);
  if (existsSync(join(out, "manifest.json")))
    throw new Error("Choose a new output directory; existing artifacts are preserved");
  mkdirSync(out, { recursive: true });
  const snapshot = join(out, "source");
  mkdirSync(snapshot, { recursive: true });
  const run = (cmd: string[]) => {
    const result = Bun.spawnSync(cmd, { cwd: root, stdout: "pipe", stderr: "pipe" });
    if (result.exitCode) throw new Error(`${cmd[0]}: ${result.stderr.toString()}`);
    return result.stdout.toString();
  };
  const graph = await buildReleaseGraph(tree, snapshot, out);
  const archive = join(out, "source.tar");
  const paths = ["docs/logo", "src/bun.ico"].filter(
    path => tree.has(path) || [...tree.files.keys()].some(file => file.startsWith(`${path}/`)),
  );
  run(["git", "archive", "--format=tar", `--output=${archive}`, tree.sha, "--", ...paths]);
  run(["tar", "-xf", archive, "-C", snapshot]);
  using database = new Database(join(out, "monorepo.sqlite"), { readonly: true });
  const sourceText = (path: string) =>
    database.query<{ content: string }, [string]>("SELECT content FROM release_files WHERE path=?").get(path)!.content;
  const version = JSON.parse(sourceText("package.json")).version as string;
  const modules = moduleNames(sourceText("src/resolve_builtins/HardcodedModule.rs"));
  const readme = releaseReadme(version, tree.sha, repo, modules);
  const artifacts = new Map<string, string | Uint8Array>();
  artifacts.set("README.md", readme);
  artifacts.set("graph-summary.json", `${JSON.stringify(graph, null, 2)}\n`);
  const metadata = {
    source: tree.sha,
    version,
    repository: repo,
    description: `Aphrody Bun ${version}: JavaScript and TypeScript runtime, bundler, test runner and package manager`,
    homepage: "https://bun.aphrody.com",
    topics: ["bun", "javascript", "typescript", "runtime", "windows"],
  };
  artifacts.set("github.json", `${JSON.stringify(metadata, null, 2)}\n`);
  const plugin = generate({ root: snapshot });
  for (const [path, data] of plugin) artifacts.set(`plugin/${path}`, data);
  artifacts.set("bun-agent-plugin.bin", pack(plugin));
  const releases: Release[] = offline
    ? []
    : JSON.parse(run(["gh", "api", "repos/aphrody-labs/bun/releases?per_page=30"]))
        .filter((r: any) => !r.draft)
        .map((r: any) => ({
          tag: r.tag_name,
          name: r.name,
          url: r.html_url,
          publishedAt: r.published_at,
          body: r.body ?? "",
          prerelease: r.prerelease,
          assets: r.assets.map((a: any) => ({ name: a.name, url: a.browser_download_url, size: a.size })),
        }));
  artifacts.set("releases.json", `${JSON.stringify(releases, null, 2)}\n`);
  const now = new Date(tree.date);
  const data = await collect({
    runtime: { repo: root, ref: tree.sha },
    org: repo.split("/")[0]!,
    author: "contact@aphrody.com",
    offline: true,
    downloadsUrl: "none",
    now,
  });
  data.runtime!.repo = repo;
  data.runtime!.guide = readme;
  artifacts.set("site-data.json", `${JSON.stringify(data, null, 2)}\n`);
  for (const [path, value] of artifacts) {
    mkdirSync(dirname(join(out, path)), { recursive: true });
    writeFileSync(join(out, path), value);
  }
  await build({
    src: snapshot,
    out: join(out, "site"),
    origin: metadata.homepage,
    commit: tree.sha,
    repo: "aphrody-labs/bun",
    releases,
    data,
    now,
  });
  cpSync(join(out, "graph-docs"), join(out, "site", "graph", "domains"), { recursive: true });
  cpSync(join(out, "graph.json"), join(out, "site", "graph", "graph.json"));
  writeFileSync(
    join(out, "site", "graph", "index.html"),
    `<!doctype html><html lang="en"><meta charset="utf-8"><title>Bun monorepo graph</title><h1>Bun monorepo graph</h1><p>Source ${tree.sha}. ${graph.files} tracked files; ${graph.readableFiles} readable source files.</p><p>${Bun.escapeHTML(graph.coverage)}</p><a href="graph.json">Domain network and coverage</a><ul>${graph.documents.map(doc => `<li><a href="domains/${doc.directory.split("/").at(-1)}/graph.html">${Bun.escapeHTML(doc.domain)}</a></li>`).join("")}</ul></html>`,
  );
  const hashes: Record<string, string> = {};
  completeReleaseKnowledge(out);
  await generateSourceMarkdown(root, tree.sha, join(out, "site", "knowledge", "markdown"));
  for (const name of ["release-server.ts", "release-cache.ts", "release-verify.ts", "release-knowledge-bench.ts"]) {
    mkdirSync(join(out, "runtime"), { recursive: true });
    writeFileSync(join(out, "runtime", name), sourceText(`scripts/aphrody/${name}`));
  }
  for (const name of ["release-nginx.ts", "release-surfaces.sh"]) {
    writeFileSync(join(out, "runtime", name), sourceText(`scripts/aphrody/deploy/${name}`));
  }
  for (const path of artifactPaths(out)) {
    hashes[path] = digest(readFileSync(join(out, path)));
  }
  const manifest = {
    schema: 1,
    source: tree.sha,
    version,
    generatedAt: tree.date,
    releaseRepository: "aphrody-labs/bun",
    releaseInventory: offline ? "offline" : "GitHub published releases",
    artifacts: hashes,
  };
  writeFileSync(join(out, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  return { readme, metadata, manifest };
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const option = (flag: string, fallback: string) => (args.includes(flag) ? args[args.indexOf(flag) + 1]! : fallback);
  const root = resolve(import.meta.dir, "../..");
  const out = resolve(option("--out", join(root, "tmp", `release-surfaces-${Date.now()}`)));
  if (args.includes("--refresh-manifest")) {
    const manifest = refreshManifest(out);
    console.log(JSON.stringify({ source: manifest.source, out, artifacts: Object.keys(manifest.artifacts).length }));
  } else {
    const result = await regenerate(
      root,
      option("--ref", "HEAD"),
      out,
      option("--repo", "aphrody-labs/bun-os"),
      args.includes("--offline"),
    );
    if (args.includes("--apply")) {
      writeFileSync(join(root, "README.md"), result.readme);
      writeFileSync(
        join(root, "packages", "bun-agent-plugin", "README.md"),
        readFileSync(join(out, "package-README.md")),
      );
      writeFileSync(join(root, ".github", "release-source.json"), `${JSON.stringify(result.metadata, null, 2)}\n`);
    }
    console.log(
      JSON.stringify({
        source: result.manifest.source,
        version: result.manifest.version,
        out,
        artifacts: Object.keys(result.manifest.artifacts).length,
      }),
    );
  }
}
