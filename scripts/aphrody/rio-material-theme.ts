import { resolve } from "node:path";

// Rust owns the theme in Material; this exports only the roles Rio draws natively.
const source = process.argv.find(arg => arg.startsWith("--source="))?.slice(9);
if (!source) throw new Error("Pass --source=<Material native ThemeExport JSON>");
const bytes = await Bun.file(resolve(source)).arrayBuffer();
const theme = JSON.parse(new TextDecoder().decode(bytes));
if (theme.schema_version !== 1 || theme.spec_version !== "2021" || theme.contrast_level !== 1)
  throw new Error("Expected the native M3 high-contrast ThemeExport (schema 1, spec 2021)");
if (
  typeof theme.seed !== "string" ||
  !/^#[\da-f]{6}$/i.test(theme.seed) ||
  ![
    "tonal-spot",
    "expressive",
    "vibrant",
    "neutral",
    "monochrome",
    "rainbow",
    "fruit-salad",
    "content",
    "fidelity",
  ].includes(theme.variant)
)
  throw new Error("Invalid native M3 seed or variant");
const roles = {
  surface: "surface",
  surface_container: "surfaceContainer",
  surface_container_high: "surfaceContainerHigh",
  on_surface: "onSurface",
  on_surface_variant: "onSurfaceVariant",
  primary: "primary",
  on_primary: "onPrimary",
  primary_container: "primaryContainer",
  on_primary_container: "onPrimaryContainer",
  outline: "outline",
  outline_variant: "outlineVariant",
};
const hash = new Bun.CryptoHasher("sha256").update(bytes).digest("hex");
const scheme = (mode: "dark" | "light") => {
  const colors = theme[mode];
  if (
    typeof colors !== "object" ||
    colors === null ||
    Array.isArray(colors) ||
    Object.keys(colors).length !== 49 ||
    !Object.values(roles).every(role => Object.hasOwn(colors, role)) ||
    !Object.values(colors).every(color => typeof color === "string" && /^#[\da-f]{6}$/i.test(color))
  )
    throw new Error(`Invalid native M3 ${mode} role map`);
  return (
    "        MaterialColors {\n" +
    Object.entries(roles)
      .map(([field, role]) => `            ${field}: rgb(0x${colors[role].slice(1)}),\n`)
      .join("") +
    "        }\n"
  );
};
const output = `// Generated by scripts/aphrody/rio-material-theme.ts from Material's Rust ThemeExport.
// Source SHA-256: ${hash}; seed ${theme.seed}; variant ${theme.variant}; contrast ${theme.contrast_level}.
use super::{rgb, MaterialColors};

pub(super) fn colors(dark: bool) -> MaterialColors {
    if dark {
${scheme("dark")}    } else {
${scheme("light")}    }
}
`;
const target = resolve(import.meta.dir, "../../src/rio/rio-backend/src/config/theme/material.rs");
if (process.argv.includes("--check")) {
  if ((await Bun.file(target).text()) !== output) throw new Error("Rio native M3 roles have drifted from Material");
} else await Bun.write(target, output);
console.log(`Rio native M3 roles ${process.argv.includes("--check") ? "verified" : "generated"}: ${hash}`);
